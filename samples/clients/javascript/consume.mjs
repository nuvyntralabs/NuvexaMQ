import { START_OFFSET, START_TAIL, connect } from "./client.mjs";

const language = "javascript";
const stream = `mailbox-${language}`;
const durable = `box-${language}`;
const tail = `tail-${language}`;
const from0 = `from0-${language}`;
const client = await connect(language);
await client.ensureStream(stream, [`${stream}.>`]);
await client.ensureConsumer(stream, durable, { filter: `${stream}.>` });
await client.publish(`${stream}.created`, Buffer.from("ack me"), "", [["content-type", Buffer.from("text/plain")]]);
await client.publish(`${stream}.created`, Buffer.from("nack me"), "", [["content-type", Buffer.from("text/plain")]]);
const batch = await client.fetch(stream, durable);
const found = new Map(batch.messages.map((message) => [message.payload.toString(), message]));
const acked = found.get("ack me");
const nacked = found.get("nack me");
await client.ack(stream, durable, acked.partition, acked.offset);
console.log("ack");
await client.nack(stream, durable, nacked.partition, nacked.offset);
console.log("nack");
const again = (await client.fetch(stream, durable)).messages.find((message) => message.payload.toString() === "nack me");
if (!again) throw new Error("nack was not redelivered");
console.log(`redelivered ${again.delivery}`);
await client.ack(stream, durable, again.partition, again.offset);
await client.reset(stream, durable, 0);
const reset = await client.fetch(stream, durable, 1);
if (reset.reset || reset.messages.length === 0) throw new Error("reset did not return a message");
console.log(`after reset offset ${reset.messages[0].offset}`);
await client.ack(stream, durable, reset.messages[0].partition, reset.messages[0].offset);
await client.release(stream, tail);
await client.ensureConsumer(stream, tail, { ephemeral: true, start: START_TAIL });
await client.publish(`${stream}.created`, Buffer.from("tail me"));
const tailed = (await client.fetch(stream, tail)).messages.find((message) => message.payload.toString() === "tail me");
if (!tailed) throw new Error("tail message was not delivered");
await client.ack(stream, tail, tailed.partition, tailed.offset);
await client.release(stream, tail);
await client.ensureConsumer(stream, from0, { start: START_OFFSET, startOffset: 0 });
console.log(`offset consumer ${from0}`);
client.close();
