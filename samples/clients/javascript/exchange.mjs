import { connect } from "./client.mjs";

const language = "javascript";
const queue = `work-${language}`;
const dead = `dead-${language}`;
const direct = `direct-${language}`;
const fanout = `fanout-${language}`;
const topic = `topic-${language}`;
const headers = `headers-${language}`;
const client = await connect(language);
await client.declareExchange("amq.direct", "direct");
await client.declareExchange(direct, "direct");
await client.declareExchange(fanout, "fanout");
await client.declareExchange(topic, "topic");
await client.declareExchange(headers, "headers");
await client.declareQueue(dead);
await client.declareQueue(queue, { ttl: 60000, maxLength: 100, deadLetter: direct, deadLetterKey: "expired" });
await client.bindQueue(direct, dead, "expired");
await client.bindQueue(direct, queue, "work.created");
await client.bindQueue(fanout, queue, "");
await client.bindQueue(topic, queue, "work.*");
await client.bindQueue(headers, queue, "", [["format", "json"], ["x-match", "all"]]);
const body = Buffer.from("routed");
const routed = [];
routed.push(...await client.publishExchange(direct, "work.created", body, "order-1"));
routed.push(...await client.publishExchange(fanout, "", body));
routed.push(...await client.publishExchange(topic, "work.created", body));
routed.push(...await client.publishExchange(headers, "", body, "", [["format", Buffer.from("json")]]));
routed.push(...await client.publishExchange("", queue, body));
if (routed.length < 5) throw new Error(`expected at least 5 receipts, got ${routed.length}`);
await client.purgeQueue(queue);
await client.deleteQueue(queue);
await client.deleteQueue(dead);
for (const name of [direct, fanout, topic, headers]) await client.deleteExchange(name);
client.close();
