<?php
require __DIR__ . "/client.php";
$language = "php";
$queue = "work-$language";
$dead = "dead-$language";
$direct = "direct-$language";
$fanout = "fanout-$language";
$topic = "topic-$language";
$headers = "headers-$language";
$client = connect_nuvexa($language);
$client->declareExchange("amq.direct", "direct");
$client->declareExchange($direct, "direct");
$client->declareExchange($fanout, "fanout");
$client->declareExchange($topic, "topic");
$client->declareExchange($headers, "headers");
$client->declareQueue($dead);
$client->declareQueue($queue, 60000, 100, $direct, "expired");
$client->bind($direct, $dead, "expired");
$client->bind($direct, $queue, "work.created");
$client->bind($fanout, $queue, "");
$client->bind($topic, $queue, "work.*");
$client->bind($headers, $queue, "", [["format", "json"], ["x-match", "all"]]);
$count = 0;
$count += count($client->publishExchange($direct, "work.created", "routed", "order-1"));
$count += count($client->publishExchange($fanout, "", "routed"));
$count += count($client->publishExchange($topic, "work.created", "routed"));
$count += count($client->publishExchange($headers, "", "routed", "", [["format", "json"]]));
$count += count($client->publishExchange("", $queue, "routed"));
if ($count < 5) throw new RuntimeException("expected at least 5 receipts, got $count");
$client->purge($queue);
$client->deleteQueue($queue);
$client->deleteQueue($dead);
foreach ([$direct, $fanout, $topic, $headers] as $name) $client->deleteExchange($name);
$client->close();
